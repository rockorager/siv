"""Generates atoms.zig and entities.zig. Run from the repository root with
the WHATWG's entities.json: python3 src/html/gen_atoms.py entities.json"""
import json, sys
# Static atoms: element and attribute names the parser, the style system,
# and layout compare by identity. Others are interned per document.
html_tags = """a abbr acronym address applet area article aside audio b base basefont bdi bdo bgsound big blink blockquote body br button canvas caption center cite code col colgroup data datalist dd del details dfn dialog dir div dl dt em embed fieldset figcaption figure font footer form frame frameset h1 h2 h3 h4 h5 h6 head header hgroup hr html i iframe image img input ins isindex kbd keygen label legend li link listing main map mark marquee math menu menuitem meta meter nav nobr noembed noframes noscript object ol optgroup option output p param picture plaintext pre progress q rb rp rt rtc ruby s samp script search section select selectedcontent slot small source span strike strong style sub summary sup svg table tbody td template textarea tfoot th thead time title tr track tt u ul var video wbr xmp""".split()
svg_tags = """altGlyph altGlyphDef altGlyphItem animateColor animateMotion animateTransform clipPath feBlend feColorMatrix feComponentTransfer feComposite feConvolveMatrix feDiffuseLighting feDisplacementMap feDistantLight feDropShadow feFlood feFuncA feFuncB feFuncG feFuncR feGaussianBlur feImage feMerge feMergeNode feMorphology feOffset fePointLight feSpecularLighting feSpotLight feTile feTurbulence foreignObject glyphRef linearGradient radialGradient textPath circle defs desc ellipse g line path polygon polyline rect stop symbol text tspan use mask pattern filter marker""".split()
math_tags = """mi mo mn ms mtext mglyph malignmark annotation-xml""".split()
attrs = """abbr accept accept-charset accesskey action align alink allow alt archive async autocapitalize autocomplete autofocus autoplay axis background bgcolor border cellpadding cellspacing char charoff charset checked cite class classid clear code codebase codetype color cols colspan compact content contenteditable controls coords crossorigin data datetime declare decoding default defer dir dirname disabled download draggable enctype encoding face for form formaction frame frameborder headers height hidden high href hreflang hspace http-equiv id inert inputmode integrity is ismap itemid itemprop itemref itemscope itemtype kind label lang language leftmargin link list loading longdesc loop low marginheight marginwidth max maxlength media method min minlength multiple muted name nohref noresize noshade novalidate nowrap open optimum pattern ping placeholder popover poster preload prompt readonly referrerpolicy rel required rev reversed role rows rowspan rules sandbox scheme scope scrolling selected shape size sizes slot span spellcheck src srcdoc srclang srcset standby start step style summary tabindex target text title topmargin translate type usemap valign value valuetype version vlink vspace width wrap xmlns xml:lang xml:space xlink:href xlink:title aria-label aria-hidden aria-labelledby aria-describedby aria-level definitionURL viewBox preserveAspectRatio fill stroke""".split()
names = []
seen = set()
for n in html_tags + svg_tags + math_tags + attrs:
    if n not in seen:
        seen.add(n); names.append(n)

def ident(n):
    if n.replace('_','').isalnum() and not n[0].isdigit() and n not in ('and','or','var','error','type','align','return','const','break','continue','test','fn','for','if','else','while','switch','struct','enum','union','true','false','null','undefined','try','catch','defer','export','extern','inline','pub','async','await','resume','suspend','nosuspend','packed','opaque','threadlocal','volatile','allowzero','anyframe','anytype','comptime','errdefer','linksection','noalias','noinline','orelse','unreachable','usingnamespace','callconv','asm','addrspace'):
        return n
    return '@"%s"' % n

out = []
out.append("//! Atoms (generated by gen_atoms.py; edit the lists there): element")
out.append("//! and attribute names that the parser, the style system, and layout compare")
out.append("//! by identity. Names outside the list are interned per document")
out.append("//! (`Interner`) and get values from `first_dynamic` on.")
out.append("")
out.append("const std = @import(\"std\");")
out.append("")
out.append("pub const Atom = enum(u32) {")
out.append("    /// No name.")
out.append("    none = 0,")
for n in names:
    out.append("    %s," % ident(n))
out.append("    _,")
out.append("")
out.append("    pub fn isStatic(a: Atom) bool {")
out.append("        return @intFromEnum(a) < first_dynamic;")
out.append("    }")
out.append("};")
out.append("")
out.append("pub const first_dynamic: u32 = %d;" % (len(names) + 1))
out.append("")
out.append("/// Names of the static atoms, by value.")
out.append("pub const static_names = [_][]const u8{")
out.append("    \"\",")
for n in names:
    out.append("    \"%s\"," % n)
out.append("};")
out.append("")
out.append("pub const static_map = std.StaticStringMap(Atom).initComptime(.{")
for n in names:
    out.append("    .{ \"%s\", Atom.%s }," % (n, ident(n)))
out.append("});")
open('src/html/atoms.zig','w').write("\n".join(out) + "\n")

# Entities.
d = json.load(open(sys.argv[1]))
items = sorted((k[1:], v['codepoints']) for k, v in d.items())
e = []
e.append("//! Named character references (generated from the WHATWG HTML Living")
e.append("//! Standard's entities.json, CC BY 4.0, by gen_atoms.py), sorted by name")
e.append("//! without the leading ampersand. Names that may appear without a semicolon")
e.append("//! (legacy) are listed both ways, as the standard lists them.")
e.append("")
e.append("pub const Entity = struct { name: []const u8, cp: [2]u21 };")
e.append("")
e.append("pub const list = [_]Entity{")
for k, cps in items:
    c = list(cps) + [0]
    e.append("    .{ .name = \"%s\", .cp = .{ %d, %d } }," % (k, c[0], c[1]))
e.append("};")
open('src/html/entities.zig','w').write("\n".join(e) + "\n")
print(len(names), len(items))
