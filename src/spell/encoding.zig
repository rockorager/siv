//! The 8-bit character sets Hunspell dictionaries may declare with SET
//! (D37), converted to UTF-8 as a dictionary is read; siv works in UTF-8
//! only. Each table maps bytes 0x80 to 0xFF to code points (U+FFFD where
//! the set has no character); the low half is ASCII in every one.

const std = @import("std");

const Table = struct {
    name: []const u8,
    high: [128]u16,
};

pub const Error = error{ OutOfMemory, UnknownEncoding };

/// Whether `name` (as SET gives it, case-insensitively, with or without
/// the dash in "ISO8859") is UTF-8.
pub fn isUtf8(name: []const u8) bool {
    return name.len == 0 or std.ascii.eqlIgnoreCase(name, "UTF-8") or std.ascii.eqlIgnoreCase(name, "UTF8");
}

fn find(name: []const u8) ?*const Table {
    for (&tables) |*t| {
        if (std.ascii.eqlIgnoreCase(t.name, name)) return t;
        // "ISO-8859-1" for "ISO8859-1".
        if (std.mem.startsWith(u8, t.name, "ISO8859") and name.len == t.name.len + 1 and
            std.ascii.eqlIgnoreCase(name[0..4], "ISO-") and std.ascii.eqlIgnoreCase(name[4..], t.name[3..])) return t;
    }
    return null;
}

/// `bytes` in UTF-8, or `bytes` itself when the encoding is UTF-8
/// (`converted` tells the caller whether to free the result).
pub fn toUtf8(gpa: std.mem.Allocator, bytes: []const u8, name: []const u8) Error!struct { []const u8, bool } {
    if (isUtf8(name)) return .{ bytes, false };
    const t = find(name) orelse return error.UnknownEncoding;
    var out: std.ArrayList(u8) = try .initCapacity(gpa, bytes.len + bytes.len / 4);
    errdefer out.deinit(gpa);
    for (bytes) |b| {
        if (b < 0x80) {
            try out.append(gpa, b);
            continue;
        }
        var buf: [4]u8 = undefined;
        const n = std.unicode.utf8Encode(t.high[b - 0x80], &buf) catch unreachable;
        try out.appendSlice(gpa, buf[0..n]);
    }
    return .{ try out.toOwnedSlice(gpa), true };
}

test "8-bit sets convert to UTF-8" {
    const gpa = std.testing.allocator;
    const latin1, const owned = try toUtf8(gpa, "Stra\xdfe", "ISO8859-1");
    defer if (owned) gpa.free(latin1);
    try std.testing.expectEqualStrings("Straße", latin1);
    const euro, _ = try toUtf8(gpa, "\xa4", "iso-8859-15");
    defer gpa.free(euro);
    try std.testing.expectEqualStrings("€", euro);
    const koi, _ = try toUtf8(gpa, "\xd3\xcc\xcf\xd7\xcf", "KOI8-R");
    defer gpa.free(koi);
    try std.testing.expectEqualStrings("слово", koi);
    try std.testing.expectError(error.UnknownEncoding, toUtf8(gpa, "x", "EBCDIC"));
}

